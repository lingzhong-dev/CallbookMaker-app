import 'dart:math' as math;

import '../models/callbook_models.dart';

class DetectSectionsStats {
  const DetectSectionsStats({
    required this.intro,
    required this.interlude,
    required this.outro,
    required this.generatedCount,
  });

  final int intro;
  final int interlude;
  final int outro;
  final int generatedCount;
}

class DetectSectionsResult {
  const DetectSectionsResult({
    required this.lines,
    required this.stats,
  });

  final List<LyricLine> lines;
  final DetectSectionsStats stats;
}

String formatGapSec(int ms) {
  final sec = math.max(0, ms) / 1000.0;
  return '${sec.toStringAsFixed(1)}s';
}

String buildSectionSummary(
  LyricLineKind kind,
  int gapMs, {
  int? intervalMs,
}) {
  if (kind == LyricLineKind.intro) {
    return '前奏空档 ${formatGapSec(gapMs)}（可标进场 Call / Mix）';
  }
  if (kind == LyricLineKind.interlude) {
    if (intervalMs != null && intervalMs > gapMs) {
      return '句间间隔 ${formatGapSec(intervalMs)} · 间奏约 ${formatGapSec(gapMs)}';
    }
    return '间奏空档 ${formatGapSec(gapMs)}（可标 Mix / 喊声）';
  }
  return '尾奏空档 ${formatGapSec(gapMs)}（可标结尾 Call / 口上）';
}

bool isAutoMaintainableSection(
  LyricLine line,
  Set<String>? protectedLineIds,
) {
  if (!line.kind.isSection) return false;
  if (!line.autoGenerated) return false;
  if (line.calls.isNotEmpty ||
      line.customShout.trim().isNotEmpty ||
      line.tailUpdraft ||
      line.alignedCalls.isNotEmpty) {
    return false;
  }
  if (protectedLineIds != null && protectedLineIds.contains(line.id)) {
    return false;
  }
  return true;
}

bool _isStickySection(LyricLine line, Set<String>? protectedLineIds) {
  if (!line.kind.isSection) return false;
  return !isAutoMaintainableSection(line, protectedLineIds);
}

/// 自动扫描相邻歌词时间戳与首尾空档，生成前奏 / 间奏 / 尾奏段落行。
/// 保留所有手工段落、已打 Call / 口上 / 尾句上升气流 / GT 警报的段落。
DetectSectionsResult detectAndMergeSections(
  List<LyricLine> rawLines, {
  SectionDetectThresholds thresholds = const SectionDetectThresholds(),
  int? totalDurationMs,
  Set<String>? protectedLineIds,
  bool onlyOutro = false,
}) {
  final lyricLines = <LyricLine>[
    for (final l in rawLines)
      if (!l.kind.isSection)
        l.copyWith(calls: [...l.calls]),
  ]..sort((a, b) => a.startTimeMs.compareTo(b.startTimeMs));

  final existingSections = <LyricLine>[
    for (final l in rawLines)
      if (l.kind.isSection)
        l.copyWith(calls: [...l.calls]),
  ]..sort((a, b) => a.startTimeMs.compareTo(b.startTimeMs));

  if (lyricLines.isEmpty) {
    final sortedAll = [...rawLines]
      ..sort((a, b) => a.startTimeMs.compareTo(b.startTimeMs));
    return DetectSectionsResult(
      lines: sortedAll,
      stats: DetectSectionsStats(
        intro: existingSections
            .where((s) => s.kind == LyricLineKind.intro)
            .length,
        interlude: existingSections
            .where((s) => s.kind == LyricLineKind.interlude)
            .length,
        outro: existingSections
            .where((s) => s.kind == LyricLineKind.outro)
            .length,
        generatedCount: 0,
      ),
    );
  }

  final stickySections = onlyOutro
      ? existingSections
      : [
          for (final s in existingSections)
            if (_isStickySection(s, protectedLineIds)) s,
        ];
  final generatedSections = <LyricLine>[];
  var seqCounter = 0;

  String nextId(String prefix, int ts) {
    seqCounter += 1;
    return 'sec-$prefix-$seqCounter-$ts';
  }

  if (!onlyOutro) {
    // 1. 前奏检测：第一句歌词前空档 >= introThresholdMs
    final firstLyric = lyricLines.first;
    if (firstLyric.startTimeMs >= thresholds.introThresholdMs) {
      final hasStickyIntro = stickySections.any(
        (s) =>
            s.kind == LyricLineKind.intro ||
            s.startTimeMs < firstLyric.startTimeMs,
      );
      if (!hasStickyIntro) {
        generatedSections.add(
          LyricLine(
            id: nextId('intro', 0),
            startTimeMs: 0,
            endTimeMs: firstLyric.startTimeMs,
            kind: LyricLineKind.intro,
            autoGenerated: true,
            text: LyricText(
              original: LyricLineKind.intro.bracketTitle,
              translation: buildSectionSummary(
                LyricLineKind.intro,
                firstLyric.startTimeMs,
              ),
            ),
          ),
        );
      }
    }

    // 2. 间奏检测：两条相邻歌词之间空的时间 >= interludeThresholdMs
    for (var i = 0; i < lyricLines.length - 1; i++) {
      final curr = lyricLines[i];
      final next = lyricLines[i + 1];
      final intervalMs = next.startTimeMs - curr.startTimeMs;
      if (intervalMs <= 0) continue;

      final stickyList = stickySections
          .where(
            (s) =>
                s.startTimeMs >= curr.startTimeMs &&
                s.startTimeMs < next.startTimeMs,
          )
          .toList();
      final stickyBetween = stickyList.firstOrNull;
      final prevSecBetween = existingSections
          .where(
            (s) =>
                s.kind == LyricLineKind.interlude &&
                s.startTimeMs > curr.startTimeMs &&
                s.startTimeMs < next.startTimeMs,
          )
          .firstOrNull;

      final hasCustomExplicitEnd =
          stickyList.isEmpty &&
          prevSecBetween == null &&
          curr.endTimeMs > curr.startTimeMs + 500 &&
          curr.endTimeMs < next.startTimeMs - 300;
      final measuredGapMs = hasCustomExplicitEnd
          ? next.startTimeMs - curr.endTimeMs
          : intervalMs;

      if (stickyBetween != null) {
        if (curr.endTimeMs > stickyBetween.startTimeMs &&
            stickyBetween.startTimeMs > curr.startTimeMs) {
          lyricLines[i] = curr.copyWith(endTimeMs: stickyBetween.startTimeMs);
        }
        continue;
      }

      if (measuredGapMs < thresholds.interludeThresholdMs) {
        if (prevSecBetween != null &&
            curr.endTimeMs == prevSecBetween.startTimeMs) {
          lyricLines[i] = curr.copyWith(endTimeMs: next.startTimeMs);
        }
        continue;
      }

      final int breakStartMs = hasCustomExplicitEnd
          ? curr.endTimeMs
          : math.max<int>(
              curr.startTimeMs + 500,
              math.min<int>(
                next.startTimeMs - 1000,
                curr.startTimeMs +
                    math.min<int>(3500, (intervalMs * 0.35).round()),
              ),
            );

      lyricLines[i] = curr.copyWith(
        endTimeMs: math.min<int>(curr.endTimeMs, breakStartMs),
      );
      final int breakDurationMs =
          math.max<int>(1000, next.startTimeMs - breakStartMs);

      generatedSections.add(
        LyricLine(
          id: nextId('interlude', breakStartMs),
          startTimeMs: breakStartMs,
          endTimeMs: next.startTimeMs,
          kind: LyricLineKind.interlude,
          autoGenerated: true,
          text: LyricText(
            original: LyricLineKind.interlude.bracketTitle,
            translation: buildSectionSummary(
              LyricLineKind.interlude,
              breakDurationMs,
              intervalMs: hasCustomExplicitEnd ? null : intervalMs,
            ),
          ),
        ),
      );
    }
  }

  // 3. 尾奏检测：仅在已知音轨真实总时长时探测末尾空档
  final adjustedStickySections = <LyricLine>[...stickySections];
  if (totalDurationMs != null && totalDurationMs > 0) {
    final lastIndex = lyricLines.length - 1;
    final lastLyric = lyricLines[lastIndex];
    final prevOutro = existingSections
        .where(
          (s) =>
              s.kind == LyricLineKind.outro &&
              s.startTimeMs >= lastLyric.startTimeMs,
        )
        .firstOrNull;
    final rawVocalEnd = prevOutro != null
        ? math.min(lastLyric.endTimeMs, prevOutro.startTimeMs)
        : lastLyric.endTimeMs;
    final vocalEndMs = math.min(
      totalDurationMs,
      math.max(lastLyric.startTimeMs + 1000, rawVocalEnd),
    );
    final outroGapMs = totalDurationMs - vocalEndMs;

    for (final s in adjustedStickySections) {
      if (s.startTimeMs > lastLyric.startTimeMs &&
          s.startTimeMs < lyricLines[lastIndex].endTimeMs) {
        lyricLines[lastIndex] = lyricLines[lastIndex].copyWith(
          endTimeMs: s.startTimeMs,
        );
      }
    }

    final stickyOutroIndices = <int>[
      for (var idx = 0; idx < adjustedStickySections.length; idx++)
        if (adjustedStickySections[idx].kind == LyricLineKind.outro ||
            adjustedStickySections[idx].startTimeMs >= lastLyric.startTimeMs)
          idx,
    ];
    if (stickyOutroIndices.isNotEmpty) {
      final lastOutroIdx = stickyOutroIndices.last;
      final existingOutro = adjustedStickySections[lastOutroIdx];
      // Only extend an auto-generated outro, and never cross any later section.
      if (existingOutro.kind == LyricLineKind.outro &&
          existingOutro.autoGenerated &&
          totalDurationMs > existingOutro.endTimeMs) {
        final hasLaterSection = adjustedStickySections.any(
          (s) =>
              s.id != existingOutro.id &&
              s.startTimeMs >= existingOutro.endTimeMs,
        );
        if (!hasLaterSection) {
          final expandedDur = totalDurationMs - existingOutro.startTimeMs;
          adjustedStickySections[lastOutroIdx] = existingOutro.copyWith(
            endTimeMs: totalDurationMs,
            text: existingOutro.text.copyWith(
              translation: buildSectionSummary(LyricLineKind.outro, expandedDur),
            ),
          );
        }
      }
    } else if (outroGapMs >= thresholds.outroThresholdMs) {
      lyricLines[lastIndex] = lastLyric.copyWith(endTimeMs: vocalEndMs);
      generatedSections.add(
        LyricLine(
          id: nextId('outro', vocalEndMs),
          startTimeMs: vocalEndMs,
          endTimeMs: totalDurationMs,
          kind: LyricLineKind.outro,
          autoGenerated: true,
          text: LyricText(
            original: LyricLineKind.outro.bracketTitle,
            translation: buildSectionSummary(LyricLineKind.outro, outroGapMs),
          ),
        ),
      );
    }
  }

  final combinedRaw = [...lyricLines, ...adjustedStickySections, ...generatedSections]
    ..sort((a, b) {
      final cmp = a.startTimeMs.compareTo(b.startTimeMs);
      if (cmp != 0) return cmp;
      return a.kind == LyricLineKind.intro ? -1 : 1;
    });

  final combined = _coalesceConsecutiveSections(
    combinedRaw,
    protectedLineIds: protectedLineIds,
  );

  return DetectSectionsResult(
    lines: combined,
    stats: DetectSectionsStats(
      intro: combined.where((s) => s.kind == LyricLineKind.intro).length,
      interlude: combined
          .where((s) => s.kind == LyricLineKind.interlude)
          .length,
      outro: combined.where((s) => s.kind == LyricLineKind.outro).length,
      generatedCount: generatedSections.length,
    ),
  );
}

/// Coalesces consecutive adjacent/overlapping auto-maintainable sections of
/// the same kind (when no lyric line sits in between). Manual, split, or
/// tagged/protected sections are never merged.
List<LyricLine> _coalesceConsecutiveSections(
  List<LyricLine> sorted, {
  Set<String>? protectedLineIds,
}) {
  if (sorted.length <= 1) return sorted;
  final out = <LyricLine>[];
  var i = 0;
  while (i < sorted.length) {
    final first = sorted[i];
    if (!first.kind.isSection) {
      out.add(first);
      i++;
      continue;
    }

    var j = i + 1;
    var groupMergedEnd = first.endTimeMs;
    if (isAutoMaintainableSection(first, protectedLineIds)) {
      while (j < sorted.length &&
          sorted[j].kind == first.kind &&
          isAutoMaintainableSection(sorted[j], protectedLineIds) &&
          sorted[j].startTimeMs <= groupMergedEnd) {
        if (sorted[j].endTimeMs > groupMergedEnd) {
          groupMergedEnd = sorted[j].endTimeMs;
        }
        j++;
      }
    }

    if (j == i + 1) {
      var single = first;
      if (single.kind == LyricLineKind.interlude &&
          out.isNotEmpty &&
          !out.last.kind.isSection) {
        final prevLyric = out.last;
        if (prevLyric.endTimeMs > single.startTimeMs) {
          out[out.length - 1] = prevLyric.copyWith(
            endTimeMs: single.startTimeMs,
          );
        }
      }
      if (single.kind == LyricLineKind.interlude &&
          j < sorted.length &&
          !sorted[j].kind.isSection &&
          single.endTimeMs > sorted[j].startTimeMs) {
        final clampedEnd = math.max(
          single.startTimeMs + 1000,
          sorted[j].startTimeMs,
        );
        single = single.copyWith(
          endTimeMs: clampedEnd,
          text: single.text.copyWith(
            translation: buildSectionSummary(
              single.kind,
              clampedEnd - single.startTimeMs,
            ),
          ),
        );
      }
      out.add(single);
      i = j;
      continue;
    }

    final group = sorted.sublist(i, j);
    final mergedStart = group.first.startTimeMs;
    var mergedEnd = groupMergedEnd;
    if (first.kind == LyricLineKind.interlude &&
        out.isNotEmpty &&
        !out.last.kind.isSection &&
        out.last.endTimeMs > mergedStart) {
      out[out.length - 1] = out.last.copyWith(endTimeMs: mergedStart);
    }
    if (first.kind == LyricLineKind.interlude &&
        j < sorted.length &&
        !sorted[j].kind.isSection &&
        mergedEnd > sorted[j].startTimeMs) {
      mergedEnd = math.max(mergedStart + 1000, sorted[j].startTimeMs);
    }

    out.add(
      group.first.copyWith(
        startTimeMs: mergedStart,
        endTimeMs: math.max(mergedStart + 1000, mergedEnd),
        autoGenerated: true,
        text: group.first.text.copyWith(
          original: first.kind.bracketTitle,
          translation: buildSectionSummary(
            first.kind,
            math.max(1000, mergedEnd - mergedStart),
          ),
        ),
      ),
    );
    i = j;
  }
  return out;
}

({int startTimeMs, int endTimeMs}) suggestManualSectionRange(
  LyricLineKind kind,
  List<LyricLine> lines, {
  String? afterLineId,
  int currentTimeMs = 0,
  int totalDurationMs = 0,
}) {
  final sorted = [...lines]
    ..sort((a, b) => a.startTimeMs.compareTo(b.startTimeMs));
  final firstLyric = sorted.where((l) => !l.kind.isSection).firstOrNull;
  final currentMs = math.max(0, currentTimeMs);

  if (kind == LyricLineKind.intro) {
    final endTimeMs =
        firstLyric != null && firstLyric.startTimeMs >= 1500
            ? firstLyric.startTimeMs
            : 8000;
    return (startTimeMs: 0, endTimeMs: endTimeMs);
  }

  if (kind == LyricLineKind.outro) {
    final last = sorted.lastOrNull;
    final int startTimeMs = last != null
        ? math.max<int>(last.endTimeMs, last.startTimeMs + 1000)
        : currentMs;
    final int endTimeMs = totalDurationMs > startTimeMs + 1000
        ? totalDurationMs
        : startTimeMs + 8000;
    return (startTimeMs: startTimeMs, endTimeMs: endTimeMs);
  }

  if (afterLineId != null) {
    final idx = sorted.indexWhere((l) => l.id == afterLineId);
    if (idx >= 0) {
      final anchor = sorted[idx];
      final next = idx + 1 < sorted.length ? sorted[idx + 1] : null;
      if (next != null && next.startTimeMs - anchor.startTimeMs >= 1400) {
        final gap = next.startTimeMs - anchor.startTimeMs;
        final int startTimeMs =
            anchor.startTimeMs + math.min<int>(3000, (gap * 0.45).round());
        return (startTimeMs: startTimeMs, endTimeMs: next.startTimeMs);
      }
      final int startTimeMs = math.max<int>(
        anchor.startTimeMs + 1000,
        anchor.endTimeMs,
      );
      return (startTimeMs: startTimeMs, endTimeMs: startTimeMs + 8000);
    }
  }

  return (startTimeMs: currentMs, endTimeMs: currentMs + 8000);
}
